/** The pinned fixture, in the shape jsqr expects. */
export function qrFixtureImageData(): {
  data: Uint8ClampedArray;
  width: number;
  height: number;
} {
  const bytes = Buffer.from(FIXTURE_RGBA_BASE64, 'base64');
  if (bytes.length !== FIXTURE_SIZE * FIXTURE_SIZE * 4) {
    throw new Error(
      `Corrupt QR fixture: expected ${FIXTURE_SIZE * FIXTURE_SIZE * 4} bytes, got ${bytes.length}`
    );
  }
  return {
    data: new Uint8ClampedArray(bytes),
    width: FIXTURE_SIZE,
    height: FIXTURE_SIZE,
  };
}
